import re
import os

auth_dir = './.lark-slides/template/pest-defense/authoring2'

def process_file(fname, replacements):
    fpath = os.path.join(auth_dir, fname)
    with open(fpath, 'r', encoding='utf-8') as f:
        content = f.read()
    for old, new in replacements:
        content = content.replace(old, new)
    # 通用清理
    content = re.sub(r'模板来自于：第一PPT[^<]*', '', content)
    content = re.sub(r'行业PPT模板[^<]*', '', content)
    content = re.sub(r'http://www\.1ppt\.com[^<]*', '', content)
    content = re.sub(r'Click to add text', '本页内容详见演讲备注。', content)
    with open(fpath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(fname + ' done')

